export function createGuideView(state: GuideState, labeled: AetheliosGuideView["labeled"] = "curated"): AetheliosGuideView {
  return {
    state,
    labeled,
    ...GUIDE_COPY[state]
  };
}

export function currentGuideView(): AetheliosGuideView {
  return createGuideView("unavailable", "curated");
}

export function validateGuidanceRequest(input: unknown): AetheliosGuidanceRequest | null {
  if (!input || typeof input !== "object") return null;
  const raw = input as Partial<AetheliosGuidanceRequest>;
  if (raw.version !== 1) return null;
  if (raw.kind !== "discovery_guidance") return null;
  if (!raw.payload || typeof raw.payload !== "object") return null;
  if ("jsx" in raw || "html" in raw || "code" in raw) return null;
  return {
    version: 1,
    kind: "discovery_guidance",
    payload: {
      businessType: typeof raw.payload.businessType === "string" ? raw.payload.businessType : "",
      qualities: Array.isArray(raw.payload.qualities) ? raw.payload.qualities.filter((item) => typeof item === "string") : [],
      selectedDirectionId: raw.payload.selectedDirectionId,
      paletteId: raw.payload.paletteId,
      visualDirectionId: raw.payload.visualDirectionId
    } as AetheliosGuidanceRequest["payload"]
  };
}

